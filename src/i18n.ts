export function isChinese(language = 'en'): boolean {
  return /^zh(?:[-_]|$)/iu.test(language);
}

export function translate(language: string | undefined, key: Key, ...args: string[]): string {
  return (isChinese(language) ? zh : en)[key].replace(/\{(\d+)\}/gu, (_, index: string) => args[Number(index)] ?? `{${index}}`);
}
